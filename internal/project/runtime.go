// portable is a core or extension skill or role and its frontmatter fields.
type portable struct {
	id, name, description string
}

// RuntimeWants returns adapter stubs in claude, codex, copilot order (I section 4.2).
func RuntimeWants(assets fs.FS, runtimes []string, models map[string]string, framework string,
	extensions []CatalogExtension,
) ([]Want, error) {
	for _, runtime := range runtimes {
		if runtime != "claude" && runtime != "codex" && runtime != "copilot" {
			return nil, fmt.Errorf("unknown runtime %q", runtime)
		}
	}
	skills, err := portables(assets, "framework/skills", true)
	if err != nil {
		return nil, err
	}
	roles, err := portables(assets, "framework/agents", false)
	if err != nil {
		return nil, err
	}
	for _, e := range extensions {
		file := path.Join(e.Dir, extensionMain(e))
		p, err := readFrontmatter(assets, file)
		if err != nil {
			return nil, fmt.Errorf("read frontmatter %s: %w", file, err)
		}
		p.id = e.Name
		if e.Kind == "agent" {
			roles = append(roles, p)
		} else {
			skills = append(skills, p)
		}
	}
	byID := func(a, b portable) int { return cmp.Compare(a.id, b.id) }
	slices.SortFunc(skills, byID)
	slices.SortFunc(roles, byID)
	var wants []Want
	if slices.Contains(runtimes, "claude") {
		wants = append(wants, claudeWants(skills, roles, models["claude"], framework)...)
	}
	if slices.Contains(runtimes, "codex") {
		codex, err := codexWants(skills, roles, models["codex"], framework)
		if err != nil {
			return nil, err
		}
		wants = append(wants, codex...)
	}
	if slices.Contains(runtimes, "copilot") {
		wants = append(wants, copilotWants(skills, roles, models["copilot"], framework)...)
	}
	return wants, nil
}

func claudeWants(skills, roles []portable, model, framework string) []Want {
	const owner = "runtime:claude"
	// CLAUDE.md is create-only (CLI-D3).
	wants := []Want{{Path: "CLAUDE.md", Owner: owner, Content: []byte("@AGENTS.md\n"), CreateOnly: true}}
	for _, s := range skills {
		var extra []string
		if s.id == "solomonar" {
			extra = append(extra, "disable-model-invocation: true")
		}
		content := skillStub(s, extra, framework)
		wants = append(wants, Want{Path: ".claude/skills/" + s.id + "/SKILL.md", Owner: owner, Content: content})
	}
	for _, r := range roles {
		var extra []string
		if r.id != "implementer" {
			extra = append(extra, "tools: Read, Grep, Glob, Bash")
		}
		if r.id == "adversarial-reviewer" && model != "" {
			extra = append(extra, "model: "+model)
		}
		source := "docs/solomonar/agents/" + r.id + ".md"
		content := stub(r, extra, fmt.Sprintf("Generated by solomonar %s from `%s`; edit that file.\n"+
			"Body edits apply directly; metadata changes need adapter regeneration. Check `solomonar help` for `sync` availability.\n"+
			"Load `AGENTS.md`, then `%s` and every file its first lines require.\n", framework, source, source))
		wants = append(wants, Want{Path: ".claude/agents/" + r.id + ".md", Owner: owner, Content: content})
	}
	return wants
}

func codexWants(skills, roles []portable, model, framework string) ([]Want, error) {
	const owner = "runtime:codex"
	var wants []Want
	for _, s := range skills {
		content := skillStub(s, nil, framework)
		wants = append(wants, Want{Path: ".agents/skills/" + s.id + "/SKILL.md", Owner: owner, Content: content})
	}
	policy := "# Generated by solomonar " + framework + "; edit docs/solomonar/skills/solomonar/SKILL.md.\n" +
		"# Body edits apply directly; metadata changes need adapter regeneration. Check solomonar help for sync availability.\npolicy:\n  allow_implicit_invocation: false\n"
	wants = append(wants, Want{Path: ".agents/skills/solomonar/agents/openai.yaml", Owner: owner, Content: []byte(policy)})
	for _, r := range roles {
		target := ".codex/agents/" + r.id + ".toml"
		source := "docs/solomonar/agents/" + r.id + ".md"
		fields := [][2]string{
			{"name", r.name},
			{"description", r.description},
			{"developer_instructions", "Load AGENTS.md, then " + source + " and every file its first lines require."},
		}
		if r.id == "adversarial-reviewer" && model != "" {
			fields = append(fields, [2]string{"model", model})
		}
		var b strings.Builder
		fmt.Fprintf(&b, "# Generated by solomonar %s from %s; edit that file.\n"+
			"# Body edits apply directly; metadata changes need adapter regeneration. Check solomonar help for sync availability.\n",
			framework, source)
		for _, f := range fields {
			value, err := tomlString(f[1])
			if err != nil {
				return nil, fmt.Errorf("render %s: %w", target, err)
			}
			fmt.Fprintf(&b, "%s = %s\n", f[0], value)
		}
		wants = append(wants, Want{Path: target, Owner: owner, Content: []byte(b.String())})
	}
	return wants, nil
}

func copilotWants(skills, roles []portable, model, framework string) []Want {
	const owner = "runtime:copilot"
	var wants []Want
	for _, s := range skills {
		// Go's quoted string escapes are also valid in YAML double-quoted scalars.
		s.name, s.description = strconv.Quote(s.name), strconv.Quote(s.description)
		var extra []string
		if s.id == "solomonar" {
			extra = append(extra, "disable-model-invocation: true")
		}
		wants = append(wants, Want{
			Path: ".github/skills/" + s.id + "/SKILL.md", Owner: owner, Content: skillStub(s, extra, framework),
		})
	}
	for _, r := range roles {
		r.name, r.description = strconv.Quote(r.name), strconv.Quote(r.description)
		extra := []string{"include-custom-instructions: true"}
		if r.id != "implementer" {
			extra = append(extra, "tools: [read, search, execute]")
		}
		if r.id == "adversarial-reviewer" && model != "" {
			extra = append(extra, "model: "+strconv.Quote(model))
		}
		source := "docs/solomonar/agents/" + r.id + ".md"
		content := stub(r, extra, fmt.Sprintf("Generated by solomonar %s from `%s`; edit that file.\n"+
			"Body edits apply directly; metadata changes need adapter regeneration. Check `solomonar help` for `sync` availability.\n"+
			"Load `AGENTS.md`, then `%s` and every file its first lines require.\n", framework, source, source))
		wants = append(wants, Want{Path: ".github/agents/" + r.id + ".agent.md", Owner: owner, Content: content})
	}
	return wants
}

func skillStub(s portable, extra []string, framework string) []byte {
	source := "docs/solomonar/skills/" + s.id + "/SKILL.md"
	return stub(s, extra, fmt.Sprintf("Generated by solomonar %s from `%s`; edit that file.\n"+
		"Body edits apply directly; metadata changes need adapter regeneration. Check `solomonar help` for `sync` availability.\n"+
		"Load `%s` and follow it.\n", framework, source, source))
}

func stub(p portable, extra []string, body string) []byte {
	lines := slices.Concat([]string{"---", "name: " + p.name, "description: " + p.description}, extra,
		[]string{"---", "", body})
	return []byte(strings.Join(lines, "\n"))
}

// tomlString quotes s as a TOML basic string, which escapes only backslash and quote.
func tomlString(s string) (string, error) {
	if strings.ContainsFunc(s, unicode.IsControl) {
		return "", fmt.Errorf("control character in %q", s)
	}
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`, nil
}

// portables reads the sorted skill directories or role files under dir, except the orchestrator (G13).
func portables(assets fs.FS, dir string, skills bool) ([]portable, error) {
	entries, err := fs.ReadDir(assets, dir)
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", dir, err)
	}
	var out []portable
	for _, e := range entries {
		if e.IsDir() != skills {
			continue
		}
		id, file := e.Name(), path.Join(dir, e.Name(), "SKILL.md")
		if !skills {
			var ok bool
			if id, ok = strings.CutSuffix(e.Name(), ".md"); !ok || id == "orchestrator" {
				continue
			}
			file = path.Join(dir, e.Name())
		}
		p, err := readFrontmatter(assets, file)
		if err != nil {
			return nil, fmt.Errorf("read frontmatter %s: %w", file, err)
		}
		p.id = id
		out = append(out, p)
	}
	return out, nil
}

func readFrontmatter(assets fs.FS, file string) (portable, error) {
	data, err := fs.ReadFile(assets, file)
	if err != nil {
		return portable{}, err
	}
	rest, ok := strings.CutPrefix(string(data), "---\n")
	header, _, closed := strings.Cut(rest, "\n---\n")
	if !ok || !closed {
		return portable{}, errors.New("no frontmatter")
	}
	var p portable
	for line := range strings.SplitSeq(header, "\n") {
		if v, ok := strings.CutPrefix(line, "name: "); ok {
			p.name = v
		} else if v, ok := strings.CutPrefix(line, "description: "); ok {
			p.description = v
		}
	}
	switch {
	case p.name == "":
		return portable{}, errors.New("missing name")
	case p.description == "":
		return portable{}, errors.New("missing description")
	}
	return p, nil
}
