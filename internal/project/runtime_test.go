func TestRuntimeWantsCopilotEscapesYAMLMetadata(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name, description, model, yaml string
	}{
		{
			name: "false", description: "null", model: "42",
			yaml: "name: 'false'\ndescription: 'null'\nmodel: '42'\n",
		},
		{
			name: "[reviewer]", description: `Review: "quotes", C:\tmp # note`, model: "model\n---\ntools: [\"*\"]",
			yaml: "name: '[reviewer]'\ndescription: 'Review: \"quotes\", C:\\tmp # note'\n" +
				"model: |-\n  model\n  ---\n  tools: [\"*\"]\n",
		},
		{
			name: "reviewer", description: "Verifică 🦉", model: "α\t\r\n\x00\a\v\b\f\x1b",
			yaml: "name: reviewer\ndescription: 'Verifică 🦉'\n" +
				`model: "α\t\r\n\u0000\u0007\u000b\b\f\u001b"` + "\n",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			assets := runtimeAssets()
			assets["framework/agents/adversarial-reviewer.md"] = frontmatter(tt.name, tt.description)
			assets["framework/skills/spec/SKILL.md"] = frontmatter(tt.name, tt.description)
			wants, err := RuntimeWants(assets, []string{"copilot"}, map[string]string{"copilot": tt.model}, framework, nil)
			require.NoError(t, err)

			role := wantedContent(t, wants, ".github/agents/adversarial-reviewer.agent.md")
			header, body, ok := strings.Cut(strings.TrimPrefix(role, "---\n"), "\n---\n")
			require.True(t, ok)
			assert.YAMLEq(t, tt.yaml+"include-custom-instructions: true\ntools: [read, search, execute]\n", header)
			assert.Contains(t, body, "Load `AGENTS.md`, then `docs/solomonar/agents/adversarial-reviewer.md`")

			skill := wantedContent(t, wants, ".github/skills/spec/SKILL.md")
			header, _, ok = strings.Cut(strings.TrimPrefix(skill, "---\n"), "\n---\n")
			require.True(t, ok)
			expected, _, _ := strings.Cut(tt.yaml, "model:")
			assert.YAMLEq(t, expected, header)
		})
	}
}

