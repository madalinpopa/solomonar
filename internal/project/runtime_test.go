func frontmatter(name, description string) *fstest.MapFile {
	return &fstest.MapFile{Data: []byte("---\nname: " + name + "\ndescription: " + description + "\n---\n\n# Body\n")}
}

func runtimeAssets() fstest.MapFS {
	return fstest.MapFS{
		"framework/skills/solomonar/SKILL.md":       frontmatter("solomonar", "Entry point."),
		"framework/skills/spec/SKILL.md":            frontmatter("spec", `Maintains "specs".`),
		"framework/skills/spec/template.md":         {Data: []byte("t\n")},
		"framework/agents/orchestrator.md":          frontmatter("orchestrator", "Coordinates."),
		"framework/agents/implementer.md":           frontmatter("implementer", "Implements."),
		"framework/agents/adversarial-reviewer.md":  frontmatter("adversarial-reviewer", `Tries "to" disprove.`),
		"framework/rules.md":                        {Data: []byte("rules\n")},
		"extensions/language/go/extension.json":     extensionJSON("go", "skill", "language", ""),
		"extensions/language/go/SKILL.md":           frontmatter("go", "Go rules."),
		"extensions/review/contrast/extension.json": extensionJSON("contrast", "agent", "review", ""),
		"extensions/review/contrast/contrast.md":    frontmatter("contrast", `Checks "contrast".`),
	}
}

func wantedContent(t *testing.T, wants []Want, path string) string {
	t.Helper()
	for _, w := range wants {
		if w.Path == path {
			return string(w.Content)
		}
	}
	require.Failf(t, "path not wanted", "%s", path)
	return ""
}

func wantedPaths(wants []Want) []string {
	var paths []string
	for _, w := range wants {
		paths = append(paths, w.Path)
	}
	return paths
}

func TestRuntimeWantsOrdersClaudeBeforeCodex(t *testing.T) {
	wants, err := RuntimeWants(runtimeAssets(), []string{"codex", "claude"}, nil, "1.2.3", nil)

	require.NoError(t, err)
	assert.Equal(t, []string{
		"CLAUDE.md",
		".claude/skills/solomonar/SKILL.md",
		".claude/skills/spec/SKILL.md",
		".claude/agents/adversarial-reviewer.md",
		".claude/agents/implementer.md",
		".agents/skills/solomonar/SKILL.md",
		".agents/skills/spec/SKILL.md",
		".agents/skills/solomonar/agents/openai.yaml",
		".codex/agents/adversarial-reviewer.toml",
		".codex/agents/implementer.toml",
	}, wantedPaths(wants))
	for _, w := range wants[:5] {
		assert.Equal(t, "runtime:claude", w.Owner, w.Path)
		assert.Equal(t, w.Path == claudePath, w.CreateOnly, w.Path)
	}
	for _, w := range wants[5:] {
		assert.Equal(t, "runtime:codex", w.Owner, w.Path)
		assert.False(t, w.CreateOnly, w.Path)
	}
}

