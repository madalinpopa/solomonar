func TestClassifyCreateOnly(t *testing.T) {
	offer := Want{Path: claudePath, Owner: "runtime:claude", Content: []byte("@AGENTS.md\n"), CreateOnly: true}
	managedClaude := &Manifest{Files: map[string]File{claudePath: {Owner: "runtime:claude", SHA256: Hash(offer.Content)}}}
	tests := []struct {
		name     string
		disk     map[string]entry
		manifest *Manifest
		change   Change
		files    map[string]File
	}{
		{
			name:   "absent is created and managed",
			change: Change{Path: claudePath, Action: ActionCreate, Owner: "runtime:claude", Content: offer.Content},
			files:  map[string]File{claudePath: {Owner: "runtime:claude", SHA256: Hash(offer.Content)}},
		},
		{
			name:   "unmanaged without the import is skipped",
			disk:   map[string]entry{claudePath: {content: "# Mine\n@AGENTS.md is elsewhere\n", mode: 0o644}},
			change: Change{Path: claudePath, Action: ActionSkip, Owner: "runtime:claude", Reason: importsLine},
			files:  map[string]File{},
		},
		{
			name:   "unmanaged with the import is skipped",
			disk:   map[string]entry{claudePath: {content: "# Mine\n@AGENTS.md\nmore\n", mode: 0o644}},
			change: Change{Path: claudePath, Action: ActionSkip, Owner: "runtime:claude", Reason: imports},
			files:  map[string]File{},
		},
		{
			name: "managed and unchanged", disk: map[string]entry{claudePath: {content: "@AGENTS.md\n", mode: 0o644}},
			manifest: managedClaude,
			change:   Change{Path: claudePath, Action: ActionUnchanged, Owner: "runtime:claude"},
			files:    managedClaude.Files,
		},
		{
			name: "managed and edited keeps the edit", disk: map[string]entry{claudePath: {content: "mine\n", mode: 0o644}},
			manifest: managedClaude,
			change:   Change{Path: claudePath, Action: ActionKeep, Owner: "runtime:claude"},
			files:    managedClaude.Files,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			root, dir := openTree(t, tt.disk)
			before := snapshot(t, dir)

			plan, files, err := Classify(root, tt.manifest, []Want{offer}, nil, nil)

			require.NoError(t, err)
			assert.Equal(t, []Change{tt.change}, plan.Changes)
			assert.Equal(t, tt.files, files)
			assert.Empty(t, plan.Conflicts())
			assert.Equal(t, before, snapshot(t, dir))
		})
	}
}

func TestClassifyCreateOnlyUnmanagedIsNotAConflict(t *testing.T) {
	root, dir := openTree(t, map[string]entry{claudePath: {content: "mine\n", mode: 0o644}})
	offer := Want{Path: claudePath, Owner: "runtime:claude", Content: []byte("@AGENTS.md\n"), CreateOnly: true}

	plan, files, err := Classify(root, nil, []Want{offer}, nil, []string{claudePath})

	assert.Equal(t, invalidResolution("%s is not a conflict", claudePath), err)
	assert.Empty(t, plan.Changes)
	assert.Nil(t, files)
	assert.Equal(t, map[string]entry{claudePath: {content: "mine\n", mode: 0o644}}, snapshot(t, dir))
}
